"""
Pydantic v2 schemas for request/response validation.
"""

from datetime import datetime
from typing import List, Optional, Literal, Dict, Any
from pydantic import BaseModel, EmailStr, Field, field_validator


# ============================================================
# AUTH
# ============================================================

class RegisterRequest(BaseModel):
    full_name: str  = Field(..., min_length=2, max_length=120, examples=["Priya Sharma"])
    email:     EmailStr = Field(..., examples=["priya@example.com"])
    password:  str  = Field(..., min_length=6, max_length=100, examples=["Secure@123"])
    phone:     Optional[str] = Field(None, max_length=25, examples=["9876543210"])


class LoginRequest(BaseModel):
    email:    EmailStr = Field(..., examples=["priya@example.com"])
    password: str      = Field(..., examples=["Secure@123"])


class UserOut(BaseModel):
    id:         int
    full_name:  str
    email:      str
    phone:      Optional[str]
    role:       str = "user"
    created_at: datetime

    model_config = {"from_attributes": True}


class ProfileUpdateRequest(BaseModel):
    full_name: str = Field(..., min_length=2, max_length=120)
    phone:     Optional[str] = Field(None, max_length=25)


class ChangePasswordRequest(BaseModel):
    current_password: str = Field(..., min_length=1)
    new_password:     str = Field(..., min_length=6, max_length=100)


class TokenOut(BaseModel):
    access_token: str
    token_type:   str = "bearer"
    user:         UserOut


# ============================================================
# LOAN APPLICATION INPUT
# ============================================================

EducationLevelType   = Literal["Graduate", "Not Graduate"]
GenderType           = Literal["Male", "Female"]
MaritalStatusType    = Literal["Married", "Single"]
EmploymentStatusType = Literal["Salaried", "Self-employed", "Unemployed"]
LoanPurposeType      = Literal["Home", "Car", "Education", "Personal"]
PropertyAreaType     = Literal["Rural", "Semiurban", "Urban"]
EmployerCategoryType = Literal["MNC", "Government", "Private", "Unemployed"]


class LoanApplicationInput(BaseModel):
    applicant_income:   float = Field(..., ge=0, examples=[50000])
    coapplicant_income: float = Field(0.0,  ge=0, examples=[20000])
    age:                int   = Field(..., ge=18, le=100, examples=[30])
    dependents:         int   = Field(0,   ge=0,  le=10, examples=[2])
    credit_score:       int   = Field(..., ge=300, le=900, examples=[750])
    existing_loans:     int   = Field(0,   ge=0,  le=20, examples=[1])
    dti_ratio:          float = Field(..., ge=0.0, le=1.0, examples=[0.30])
    savings:            float = Field(..., ge=0, examples=[300000])
    collateral_value:   float = Field(..., ge=0, examples=[500000])
    loan_amount:        float = Field(..., gt=0, examples=[200000])
    loan_term:          int   = Field(..., ge=12, le=480, examples=[360])
    education_level:    EducationLevelType   = "Graduate"
    gender:             GenderType           = "Male"
    marital_status:     MaritalStatusType    = "Single"
    employment_status:  EmploymentStatusType = "Salaried"
    loan_purpose:       LoanPurposeType      = "Home"
    property_area:      PropertyAreaType     = "Urban"
    employer_category:  EmployerCategoryType = "MNC"


